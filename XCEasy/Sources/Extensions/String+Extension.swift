import Foundation

// MARK: - String Extension

/// Extension for String type providing common string constants.
public extension String {

    /// A space character.
    static var space: String {
        " "
    }

    /// A non-breaking space character.
    static var nonBreakSpace: String {
        " "
    }

    /// A plus sign.
    static var plus: String {
        "+"
    }

    /// A hyphen character.
    static var hyphen: String {
        "-"
    }

    /// A minus sign.
    static var minus: String {
        "−"
    }

    /// A dash character.
    static var dash: String {
        "–"
    }

    /// A forward slash.
    static var slash: String {
        "/"
    }

    /// A colon.
    static var colon: String {
        ":"
    }

    /// A newline character.
    static var newLine: String {
        "\n"
    }

    /// A tab character.
    static var tab: String {
        "\t"
    }

    /// An empty string.
    static var empty: String {
        ""
    }

    /// A comma.
    static var comma: String {
        ","
    }
}
